type sanitizedResolverError struct {
	cause error
}

func (e *sanitizedResolverError) Error() string {
	return "resolve supplemental runtime paths failed"
}

func (e *sanitizedResolverError) Unwrap() error {
	return e.cause
}

func (e sanitizedResolverError) Format(state fmt.State, verb rune) {
	const message = "resolve supplemental runtime paths failed"
	if verb == 'q' {
		_, _ = fmt.Fprintf(state, "%q", message)
		return
	}
	_, _ = fmt.Fprint(state, message)
}

// RuntimeSupplementalPaths are generated by trusted server-side
// materialization that is intentionally outside the current Materializer.
type RuntimeSupplementalPaths struct {
	Bootstrap   runtime.PathPair
	ModelSecret runtime.PathPair
}

func (p RuntimeSupplementalPaths) String() string {
	return "RuntimeSupplementalPaths{Bootstrap:[REDACTED] ModelSecret:[REDACTED]}"
}

func (p RuntimeSupplementalPaths) GoString() string {
	return p.String()
}

type RuntimeSupplementalPathResolverFunc func(
	context.Context,
	control.Identity,
	MaterializedSession,
) (RuntimeSupplementalPaths, error)

// TrustedSupplementalResolverOptions contains only Backend-issued model route
// data and the known root-only model key bind source.
type TrustedSupplementalResolverOptions struct {
	Mapper              runtime.PathMapper
	ModelSecretSource   runtime.PathPair
	ModelKey            []byte
	ModelSecretOwnerUID func(*os.File) (uint32, error)
	UpstreamModel       string
	UpstreamAPIBase     string
	AgentProfile        agentprofile.Profile
	NewToken            func() (string, error)
}

func (o TrustedSupplementalResolverOptions) String() string {
	return fmt.Sprintf(
		"TrustedSupplementalResolverOptions{AgentProfile:%q Private:[REDACTED]}",
		o.AgentProfile,
	)
}

func (o TrustedSupplementalResolverOptions) GoString() string {
	return o.String()
}

// NewTrustedSupplementalPathResolver writes one root-only bootstrap per
// session. The upstream key is intentionally never read, serialized, or added
// to a Worker environment; the Worker receives it only through ModelSecret.
func NewTrustedSupplementalPathResolver(
	options TrustedSupplementalResolverOptions,
) (RuntimeSupplementalPathResolverFunc, error) {
	if options.UpstreamModel == "" || strings.TrimSpace(options.UpstreamModel) != options.UpstreamModel ||
		options.UpstreamAPIBase == "" || strings.TrimSpace(options.UpstreamAPIBase) != options.UpstreamAPIBase {
		return nil, fmt.Errorf("trusted upstream model route is required")
	}
	if _, err := agentprofile.Parse(string(options.AgentProfile)); err != nil {
		return nil, err
	}
	if err := validateTrustedPathPair(options.Mapper, options.ModelSecretSource); err != nil {
		return nil, err
	}
	if len(options.ModelKey) == 0 || len(options.ModelKey) > 4<<10 ||
		strings.ContainsRune(string(options.ModelKey), '\x00') {
		return nil, fmt.Errorf("trusted model key must contain one bounded token")
	}
	modelKey := append([]byte(nil), options.ModelKey...)
	modelSecretOwnerUID := options.ModelSecretOwnerUID
	if modelSecretOwnerUID == nil {
		modelSecretOwnerUID = fileOwnerUID
	}
	newToken := options.NewToken
	if newToken == nil {
		newToken = newSupplementalToken
	}
	return func(ctx context.Context, identity control.Identity, _ MaterializedSession) (RuntimeSupplementalPaths, error) {
		if err := ctx.Err(); err != nil {
			return RuntimeSupplementalPaths{}, err
		}
		bootstrap, err := options.Mapper.SessionPath(identity.WorkerSessionID, "bootstrap.json")
		if err != nil {
			return RuntimeSupplementalPaths{}, err
		}
		modelSecret, err := options.Mapper.SessionPath(identity.WorkerSessionID, "model-secret")
		if err != nil {
			return RuntimeSupplementalPaths{}, err
		}
		if modelSecret == options.ModelSecretSource {
			return RuntimeSupplementalPaths{}, fmt.Errorf("trusted model secret destination must be session-scoped")
		}
		proxyToken, err := newToken()
		if err != nil {
			return RuntimeSupplementalPaths{}, fmt.Errorf("generate LiteLLM proxy token: %w", err)
		}
		modelSinkToken, err := newToken()
		if err != nil {
			return RuntimeSupplementalPaths{}, fmt.Errorf("generate model sink token: %w", err)
		}
		if !validSupplementalToken(proxyToken) || !validSupplementalToken(modelSinkToken) {
			return RuntimeSupplementalPaths{}, fmt.Errorf("generate trusted runtime token: invalid token")
		}
		payload, err := json.Marshal(struct {
			UpstreamModel   string `json:"upstream_model"`
			UpstreamAPIBase string `json:"upstream_api_base"`
			ProxyToken      string `json:"proxy_token"`
			ModelSinkToken  string `json:"model_sink_token"`
			AgentProfile    string `json:"agent_profile"`
		}{
			UpstreamModel:   options.UpstreamModel,
			UpstreamAPIBase: options.UpstreamAPIBase,
			ProxyToken:      proxyToken,
			ModelSinkToken:  modelSinkToken,
			AgentProfile:    options.AgentProfile.String(),
		})
		if err != nil {
			return RuntimeSupplementalPaths{}, fmt.Errorf("encode trusted runtime bootstrap: %w", err)
		}
		if err := writeSessionModelSecret(modelSecret.ContainerPath, modelKey, modelSecretOwnerUID); err != nil {
			return RuntimeSupplementalPaths{}, err
		}
		removeModelSecret := true
		defer func() {
			if removeModelSecret {
				_ = os.Remove(modelSecret.ContainerPath)
			}
		}()
		file, err := os.OpenFile(bootstrap.ContainerPath, os.O_WRONLY|os.O_CREATE|os.O_EXCL, 0o600)
		if err != nil {
			return RuntimeSupplementalPaths{}, fmt.Errorf("create trusted runtime bootstrap: %w", err)
		}
		if _, err := file.Write(append(payload, '\n')); err != nil {
			_ = file.Close()
			_ = os.Remove(bootstrap.ContainerPath)
			return RuntimeSupplementalPaths{}, fmt.Errorf("write trusted runtime bootstrap: %w", err)
		}
		if err := file.Close(); err != nil {
			_ = os.Remove(bootstrap.ContainerPath)
			return RuntimeSupplementalPaths{}, fmt.Errorf("close trusted runtime bootstrap: %w", err)
		}
		removeModelSecret = false
		return RuntimeSupplementalPaths{Bootstrap: bootstrap, ModelSecret: modelSecret}, nil
	}, nil
}

func writeSessionModelSecret(
	path string,
	modelKey []byte,
	ownerUID func(*os.File) (uint32, error),
) error {
	file, err := os.OpenFile(path, os.O_WRONLY|os.O_CREATE|os.O_EXCL, 0o400)
	if err != nil {
		return fmt.Errorf("create trusted session model secret: %w", err)
	}
	cleanup := true
	defer func() {
		_ = file.Close()
		if cleanup {
			_ = os.Remove(path)
		}
	}()
	if _, err := file.Write(modelKey); err != nil {
		return fmt.Errorf("write trusted session model secret: %w", err)
	}
	if err := file.Sync(); err != nil {
		return fmt.Errorf("sync trusted session model secret: %w", err)
	}
	uid, err := ownerUID(file)
	if err != nil {
		return fmt.Errorf("inspect trusted session model secret owner: %w", err)
	}
	if uid != 0 {
		return fmt.Errorf("trusted session model secret must be root-owned")
	}
	if err := file.Close(); err != nil {
		return fmt.Errorf("close trusted session model secret: %w", err)
	}
	cleanup = false
	return nil
}

func fileOwnerUID(file *os.File) (uint32, error) {
	info, err := file.Stat()
	if err != nil {
		return 0, err
	}
	stat, ok := info.Sys().(*syscall.Stat_t)
	if !ok {
		return 0, fmt.Errorf("file ownership metadata is unavailable")
	}
	return stat.Uid, nil
}

func validateTrustedPathPair(mapper runtime.PathMapper, pair runtime.PathPair) error {
	for _, path := range []string{mapper.ContainerDataRoot, mapper.HostDataRoot, pair.ContainerPath, pair.HostPath} {
		if path == "" || !filepath.IsAbs(path) || filepath.Clean(path) != path {
			return fmt.Errorf("trusted supplemental path must be clean and absolute")
		}
	}
	containerRelative, containerErr := filepath.Rel(mapper.ContainerDataRoot, pair.ContainerPath)
	hostRelative, hostErr := filepath.Rel(mapper.HostDataRoot, pair.HostPath)
	if containerErr != nil || hostErr != nil || containerRelative == "." ||
		containerRelative == ".." || hostRelative == ".." ||
		strings.HasPrefix(containerRelative, ".."+string(filepath.Separator)) ||
		strings.HasPrefix(hostRelative, ".."+string(filepath.Separator)) ||
		containerRelative != hostRelative {
		return fmt.Errorf("trusted model secret must map below both data roots")
	}
	return nil
}

func newSupplementalToken() (string, error) {
	bytes := make([]byte, 32)
	if _, err := rand.Read(bytes); err != nil {
		return "", err
	}
	return base64.RawURLEncoding.EncodeToString(bytes), nil
}

func validSupplementalToken(value string) bool {
	return value != "" && strings.TrimSpace(value) == value && !strings.ContainsAny(value, "\r\n\x00")
}

type runtimeProvisionerAdapter struct {
	provisioner runtime.Provisioner
	resolve     RuntimeSupplementalPathResolverFunc
}

// NewRuntimeProvisionerAdapter reconciles the temporary scheduler seam with
// runtime.Provisioner without widening public request contracts.
func NewRuntimeProvisionerAdapter(
	provisioner runtime.Provisioner,
	resolve RuntimeSupplementalPathResolverFunc,
) RuntimeProvisioner {
	return &runtimeProvisionerAdapter{provisioner: provisioner, resolve: resolve}
}

func (a *runtimeProvisionerAdapter) Provision(ctx context.Context, request RuntimeProvisionRequest) error {
	if a.provisioner == nil || a.resolve == nil {
		return ErrNotConfigured
	}
	supplemental, err := a.resolve(ctx, request.Identity, request.Materialized)
	if err != nil {
		return &sanitizedResolverError{cause: err}
	}
	_, err = a.provisioner.Start(ctx, runtime.ProvisionRequest{
		Identity:    runtimeIdentity(request.Identity),
		WorkerToken: request.WorkerToken,
		WorkingCopy: request.Materialized.WorkingCopy,
		AgentState:  request.Materialized.AgentState,
		TraceSpool:  request.Materialized.TraceSpool,
		Bootstrap:   supplemental.Bootstrap,
		ModelSecret: supplemental.ModelSecret,
	})
	return err
}

func (a *runtimeProvisionerAdapter) Cleanup(ctx context.Context, identity control.Identity) error {
	if a.provisioner == nil {
		return ErrNotConfigured
	}
	return a.provisioner.Cleanup(ctx, runtimeIdentity(identity))
}

func runtimeIdentity(identity control.Identity) runtime.RuntimeIdentity {
	return runtime.RuntimeIdentity{
		WorkerSessionID:   identity.WorkerSessionID,
		WorkerRunID:       identity.WorkerRunID,
		RuntimeInstanceID: identity.RuntimeInstanceID,
		RuntimeGeneration: identity.RuntimeGeneration,
	}
}
